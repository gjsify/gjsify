// Regenerate src/data/adwaita-tokens.ts from the stylesheet that DECLARES the tokens,
// so the documented theming contract cannot drift from the shipped one.
//
// ADR 0010 decision 2 makes the `--adw-*` / `--*` custom properties the public
// theming contract of `@gjsify/adwaita-web` — the sanctioned way to re-theme, and the
// counterpart to the light-DOM boundary reset. A contract nobody can read is not one,
// so it belongs on the website; a contract TYPED OUT on the website is the drift this
// repo keeps paying for (two live counts had to be deleted from the status notes the
// same week). Hence: read `scss/_variables.scss`, emit data, render the data.
//
// The source is the `light-theme` MIXIN's declarations and the `// Section` comments
// it already carries. A mixin rather than a bare `:root` block because `.theme-light`
// has to include the same tokens for a subtree opt-out — the stylesheet says why. The
// dark block re-declares the same NAMES with other values and is deliberately not read
// here: the contract is the name and what it means, and listing each token twice would
// say the opposite.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..');
const source = join(repoRoot, 'packages/web/adwaita-web/scss/_variables.scss');
const outPath = join(here, '..', 'src', 'data', 'adwaita-tokens.ts');

const css = readFileSync(source, 'utf8');

// The `light-theme` mixin — the light defaults. Braces do not nest inside it.
const rootBlock = css.match(/@mixin\s+light-theme\s*\{([\s\S]*?)\n\}/);
if (!rootBlock) {
    console.error(
        `generate-theming-tokens: no \`@mixin light-theme\` in ${source} — the scan is broken, not the stylesheet.`,
    );
    process.exit(1);
}

/**
 * Group tokens by the `// ---- Name ----`-style section comments the stylesheet
 * already carries, so the page's sections are the stylesheet's own and a new group
 * needs no edit here.
 */
const groups = [];
let current = { title: 'General', tokens: [] };
for (const line of rootBlock[1].split('\n')) {
    const heading = line.match(/^\s*\/\/\s*(?:-+\s*)?([A-Z][^-\n]*?)\s*(?:-+)?\s*$/);
    if (heading) {
        if (current.tokens.length > 0) groups.push(current);
        current = { title: heading[1].trim(), tokens: [] };
        continue;
    }
    // Name and value only. The stylesheet's comments sit ABOVE their declarations and
    // are paragraphs about GTK internals, not one-line captions — a `note` field was
    // written here first and measured EMPTY for all 67 tokens, so it is not pretended.
    const decl = line.match(/^\s*(--[a-z0-9-]+)\s*:\s*([^;]+);/);
    if (decl) current.tokens.push({ name: decl[1], value: decl[2].trim() });
}
if (current.tokens.length > 0) groups.push(current);

const total = groups.reduce((sum, group) => sum + group.tokens.length, 0);
if (total === 0) {
    console.error('generate-theming-tokens: parsed the mixin and found no tokens — that is a broken parse.');
    process.exit(1);
}

const out = `// AUTO-GENERATED by website/scripts/generate-theming-tokens.mjs.
// DO NOT EDIT BY HAND — re-run \`gjsify run generate:tokens\` (or the build pre-step).
//
// Source: packages/web/adwaita-web/scss/_variables.scss, the \`light-theme\` mixin.
// ADR 0010 decision 2: these custom properties ARE the public theming contract.

export interface AdwToken {
    /** The custom property, e.g. \`--accent-bg-color\`. */
    name: string;
    /** Its light-mode default. Dark mode re-declares the same names. */
    value: string;
}

export interface AdwTokenGroup {
    title: string;
    tokens: AdwToken[];
}

export const ADWAITA_TOKEN_GROUPS: AdwTokenGroup[] = ${JSON.stringify(groups, null, 4)};

/** How many tokens the contract carries — derived, never typed. */
export const ADWAITA_TOKEN_COUNT = ${total};
`;

// The generated body is `JSON.stringify` output — quoted keys, no trailing
// commas — while the committed file is oxfmt's. Left alone, every `run start`
// and every `run build` rewrote a TRACKED file into a style the formatter
// disagrees with, so simply viewing the site left the tree dirty and a later
// `git add -A` would commit the churn. Formatting here rather than matching
// oxfmt's style by hand: a hand-copied style is a second copy of the formatter's
// rules, and it drifts the first time they change.
function formatGenerated(path) {
    const result = spawnSync('gjsify', ['format', path], { stdio: 'inherit' });
    if (result.error || result.status !== 0) {
        console.warn(`  note: could not run \`gjsify format ${path}\` — the file is written but unformatted.`);
    }
}

// `--check` compares instead of writing, which is what makes the generation HELD
// rather than merely available: this script is a `website` npm script and ran in no
// workflow at all, so the committed data could disagree with the stylesheet
// indefinitely while `theming.mdx` quoted a count derived from it.
//
// THE DATA, not the text. A byte comparison would need this process to run the
// formatter, and measured, with the workspace `node_modules/.bin` off PATH a GLOBAL
// `gjsify` gets picked up instead and dies on a missing biome — reporting a
// perfectly current file as STALE. Normalising whitespace is not enough either, and
// the comment above says why: this generator emits `JSON.stringify` output while the
// committed file is oxfmt's, so they differ in QUOTE STYLE (measured: 319 single
// quotes committed against the generator's double) and in 107 trailing commas.
//
// So the check extracts the `--token: value` pairs from both sides, accepting either
// quote style, and compares those. That is also the question worth asking: the
// contract is the token names and what they mean, and reformatting is not a change
// to it. `gjsify format --check` holds the style, tree-wide, on its own.
if (process.argv.includes('--check')) {
    // `{ name: '--window-bg-color', value: '#fafafb' }` — an object per token, not a
    // `'--x': 'v'` map. Either quote style, so the same reader works on both sides.
    const pairs = (text) =>
        [...text.matchAll(/["']?name["']?\s*:\s*['"](--[a-z0-9-]+)['"]\s*,\s*["']?value["']?\s*:\s*['"]([^'"]*)['"]/g)]
            .map(([, name, value]) => `${name}=${value}`)
            .sort()
            .join('\n');
    const committed = pairs(readFileSync(outPath, 'utf8'));
    const generated = pairs(out);
    if (committed === generated && committed.length > 0) {
        console.log(`generate-theming-tokens --check: OK (${total} tokens in ${groups.length} groups)`);
        process.exit(0);
    }
    if (committed.length === 0) {
        console.error(
            'generate-theming-tokens --check: read NO tokens out of the committed file. That is the\n' +
                '  reader broken, not the data stale — an empty comparison would pass against anything.',
        );
        process.exit(1);
    }
    console.error(
        'generate-theming-tokens --check: src/data/adwaita-tokens.ts is STALE.\n' +
            '  Regenerate it: node website/scripts/generate-theming-tokens.mjs\n' +
            '  The documented theming contract would otherwise disagree with the shipped stylesheet.',
    );
    process.exit(1);
}

writeFileSync(outPath, out, 'utf8');
formatGenerated(outPath);
console.log(`generate-theming-tokens: wrote ${outPath} (${total} tokens in ${groups.length} groups)`);
