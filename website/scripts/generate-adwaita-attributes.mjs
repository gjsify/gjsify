// Regenerate src/data/adwaita-attributes.ts from the elements that DECLARE the
// attributes, so the documented markup surface cannot drift from the shipped one.
//
// THE INCIDENT
//
// The gallery pages describe each widget's attributes in prose, by hand. Measured
// on 2026-08-23 across the 37 `<AdwWidget>` blocks that join to an element: 110 of
// the observed attributes are named somewhere on their page and **54 are not**.
// Whole visual surfaces were missing — all four of `<adw-toolbar-view>`'s
// (`top-bar-style`, `bottom-bar-style`, and both `extend-content-to-*-edge`) appear
// nowhere on the entire site, and `<adw-overlay-split-view>` is short eight,
// including `breakpoint`, the one attribute that makes the adaptive collapse its own
// section is about happen at all. Nothing could see it: no script in the repo read
// an `observedAttributes` literal, and no script read an attribute name out of an
// `.mdx`.
//
// A hand is not a mechanism, and 54 hand-written table rows would be 54 more things
// to drift. So: read the elements, emit data, render the data — the same shape
// `generate-theming-tokens.mjs` already uses for the theming contract, and for the
// reason its own header gives ("a contract TYPED OUT on the website is the drift
// this repo keeps paying for").
//
// WHY THE READER LIVES IN scripts/adwaita-elements.mjs
//
// That module is the ONE reader of what each renderer ships, and its own header
// records what three separate derivations cost: 65 elements against 50, with the
// smaller answer feeding the published widget matrix. `observedAttributes()` is
// asked here and answered there, joined through the same `widgetClass` rule that
// module already THROWS on when a tag and its class disagree — so this generator
// cannot quietly miss an element the pillar registers.
//
// Four declaration shapes exist in the pillar and all four are resolved, because
// each unresolved one would be an element documenting nothing while looking
// documented: a plain literal, a literal behind a `(): string[]` return type, a
// `return NAMED_CONSTANT;`, and `[...AdwEntryRow.observedAttributes, 'revealed']` —
// a spread whose base class lives in a different file.
//
// Usage: node website/scripts/generate-adwaita-attributes.mjs [--check]

import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { observedAttributes } from '../../scripts/adwaita-elements.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..');
const outPath = join(here, '..', 'src', 'data', 'adwaita-attributes.ts');

const { byTag, unreadable } = observedAttributes(repoRoot);

if (unreadable.length > 0) {
    console.error(
        `generate-adwaita-attributes: ${unreadable.length} element(s) declare an observedAttributes\n` +
            'this reader cannot resolve. An element it cannot read would render an EMPTY attribute\n' +
            'table, which reads as "this widget has no attributes" — the one answer that is never\n' +
            'true and never checkable. Extend the reader in scripts/adwaita-elements.mjs:\n' +
            unreadable.map((u) => `  - ${u}`).join('\n'),
    );
    process.exit(1);
}

const tags = [...byTag.keys()].sort();
const total = [...byTag.values()].reduce((n, attrs) => n + attrs.length, 0);

const body = tags
    .map(
        (tag) =>
            `    '${tag}': [${byTag
                .get(tag)
                .map((a) => `'${a}'`)
                .join(', ')}],`,
    )
    .join('\n');

const out = `// GENERATED by website/scripts/generate-adwaita-attributes.mjs — do not edit.
//
// The attributes each \`adw-*\` element observes, read from its own
// \`observedAttributes\`. \`scripts/check-generated-website-data.mjs\` fails when this
// file no longer matches the elements, so the table on a gallery page cannot drift
// from the markup a reader can actually write.

/** Registered tag -> the attributes that element observes, in declaration order. */
export const ADWAITA_ATTRIBUTES: Readonly<Record<string, readonly string[]>> = {
${body}
};

/** How many attributes the web pillar observes in total. */
export const ADWAITA_ATTRIBUTE_COUNT = ${total};

/** How many elements the pillar registers. An element with none is still an entry. */
export const ADWAITA_ELEMENT_COUNT = ${tags.length};
`;

// Formatted through the repo's own formatter rather than by matching its style
// here: a hand-copied style is a second copy of the formatter's rules and drifts
// the first time they change. Same reasoning, same helper, as
// generate-theming-tokens.mjs.
function formatGenerated(path) {
    const result = spawnSync('gjsify', ['format', path], { stdio: 'inherit' });
    if (result.error || result.status !== 0) {
        console.warn(`  note: could not run \`gjsify format ${path}\` — the file is written but unformatted.`);
    }
}

if (process.argv.includes('--check')) {
    // THE DATA, not the text. A byte comparison would need this process to run the
    // formatter, and with the workspace `node_modules/.bin` off PATH a GLOBAL
    // `gjsify` gets picked up instead and dies on a missing biome — reporting a
    // current file as STALE. Normalising whitespace is not enough either: oxfmt
    // wraps the long rows and adds a trailing comma inside the array, so the
    // committed `['a', 'b',]` and the emitted `['a', 'b']` differ by a character
    // whitespace-normalisation keeps.
    //
    // The contract is the tag and the attributes it observes. Reformatting is not a
    // change to it, and `gjsify format --check` holds the style tree-wide anyway.
    const rows = (text) =>
        [...text.matchAll(/'(adw-[a-z-]+)'\s*:\s*\[([^\]]*)\]/g)]
            .map(([, tag, list]) => `${tag}=${[...list.matchAll(/'([^']+)'/g)].map(([, a]) => a).join(',')}`)
            .sort()
            .join('\n');
    const committed = rows(readFileSync(outPath, 'utf8'));
    if (committed.length === 0) {
        console.error(
            'generate-adwaita-attributes --check: read NO rows out of the committed file. That is the\n' +
                '  reader broken, not the data stale — an empty comparison would pass against anything.',
        );
        process.exit(1);
    }
    if (committed === rows(out)) {
        console.log(`generate-adwaita-attributes --check: OK. ${tags.length} element(s), ${total} attribute(s).`);
        process.exit(0);
    }
    console.error(
        'generate-adwaita-attributes --check: src/data/adwaita-attributes.ts is STALE.\n' +
            '  Regenerate it: node website/scripts/generate-adwaita-attributes.mjs\n' +
            '  A stale table documents attributes the elements no longer take, or hides ones they do.',
    );
    process.exit(1);
}

writeFileSync(outPath, out, 'utf8');
formatGenerated(outPath);
console.log(`✓ Generated src/data/adwaita-attributes.ts (${tags.length} elements, ${total} attributes)`);
