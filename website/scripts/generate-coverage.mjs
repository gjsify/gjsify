// Regenerate src/data/coverage.ts from the project's status DATA, so the
// website's pillar-coverage bars sit two derivation steps from the package
// manifests with no hand-typed number in between.
//
// SOURCE: `statusSummary()` in `scripts/generate-status.mjs` — the same
// function that produces the Summary table of the rendered status snapshot,
// returning `{category, total, full, partial, stub}` as NUMBERS.
//
// It used to read STATUS.md and re-parse that rendered Markdown table,
// recovering `33` out of a formatted `33 (80%)` cell. Two things killed that:
// STATUS.md is no longer committed (it is a gitignored on-demand render — see
// ADR 0016 and its amendment), so on a fresh checkout there is no file to
// parse; and parsing a presentation format to recover the integer that
// produced it was always a lossy round trip that existed only because Markdown
// was the sole artifact on offer. Importing the counts directly also means the
// authored data is VALIDATED on the way through — `statusSummary()` throws
// rather than emitting numbers derived from data `audit-runtimes --check`
// would reject.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { statusSummary } from '../../scripts/generate-status.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..');
const outPath = join(here, '..', 'src', 'data', 'coverage.ts');

const pillars = statusSummary(repoRoot);

// Header categories we treat as "pillars" with a real Full/Partial/Stub split.
// The table includes meta + native-bridge rows that are 1-of-1 or all-Full —
// keep them so the totals line up, but the component decides which to render
// in the pillar overview vs. the supplementary detail strip.
const out = `// AUTO-GENERATED by website/scripts/generate-coverage.mjs.
// DO NOT EDIT BY HAND — re-run \`gjsify run generate-coverage\` (or the build
// pre-step) to refresh.
//
// Source: \`statusSummary()\` in scripts/generate-status.mjs — the authored
// status data under status/ combined with facts derived from the package
// manifests. Each entry captures the Total / Full / Partial / Stub split for
// one category.

export interface PillarCoverage {
    /** Category label, as the status generator names it (verbatim). */
    category: string;
    /** Total surveyed entries in this pillar. */
    total: number;
    /** Fully implemented entries. */
    full: number;
    /** Partially implemented entries (core works; specific subsystems open). */
    partial: number;
    /** Stub-only entries (deprecated / browser-irrelevant / no-op). */
    stub: number;
}

export const pillarCoverage: readonly PillarCoverage[] = ${JSON.stringify(pillars, null, 4)};

/** Pillars meaningful as a top-level coverage breakdown — meta + native-bridge
 *  rows are excluded (they aren't multi-entry "categories" that benefit from a
 *  bar). Keeps the visual hierarchy clean. */
export const overviewPillars: readonly PillarCoverage[] = pillarCoverage.filter(
    (p) => !/(meta|native bridges?)$/i.test(p.category),
);

/** Aggregate over the overview-tier pillars (all rendered in the bar grid). */
export function tallyOverview(): {
    total: number; full: number; partial: number; stub: number;
    implementedPct: number;
} {
    const acc = { total: 0, full: 0, partial: 0, stub: 0 };
    for (const p of overviewPillars) {
        acc.total += p.total; acc.full += p.full;
        acc.partial += p.partial; acc.stub += p.stub;
    }
    const implementedPct = acc.total === 0 ? 0
        : Math.round(((acc.full + acc.partial) / acc.total) * 100);
    return { ...acc, implementedPct };
}
`;

writeFileSync(outPath, out, 'utf8');
console.log(`generate-coverage: wrote ${outPath} (${pillars.length} pillars)`);
