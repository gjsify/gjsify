// Regenerate src/data/coverage.ts from STATUS.md's "Summary" table so the
// website's pillar-coverage bars stay in lockstep with the project's
// canonical status snapshot.
//
// The Summary table looks like:
//
//   | Category | Total | Full | Partial | Stub |
//   |----------|-------|------|---------|------|
//   | Node.js APIs | 41 | 33 (80%) | 5 (12%) | 3 (7%) |
//   | Web APIs | 18 | 16 (89%) | 2 (11%) | — |
//   ...
//
// Cell values may be a bare integer, an integer with a `(NN%)` suffix, or `—`.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..');
const statusPath = join(repoRoot, 'STATUS.md');
const outPath = join(here, '..', 'src', 'data', 'coverage.ts');

const statusSrc = readFileSync(statusPath, 'utf8');

// Locate the Summary table — first table after the `## Summary` heading.
const summaryStart = statusSrc.indexOf('## Summary');
if (summaryStart === -1) throw new Error('Could not find "## Summary" heading in STATUS.md');
const after = statusSrc.slice(summaryStart);
const tableMatch = after.match(/\| Category \|[^\n]+\n\|[-| ]+\n((?:\|[^\n]+\n)+)/);
if (!tableMatch) throw new Error('Could not match the Category/Total/Full/Partial/Stub table');

const rows = tableMatch[1].trim().split('\n');

/** Parse a cell like "33 (80%)", "16", "—", or "5 (terminal, sab, …)". */
function parseCell(raw) {
    const trimmed = raw.trim();
    if (trimmed === '—' || trimmed === '-' || trimmed === '') return 0;
    const m = trimmed.match(/^(\d+)/);
    return m ? Number(m[1]) : 0;
}

const pillars = rows.map((row) => {
    const cols = row
        .split('|')
        .slice(1, -1)
        .map((c) => c.trim());
    const [category, total, full, partial, stub] = cols;
    return {
        category,
        total: Number(total),
        full: parseCell(full),
        partial: parseCell(partial),
        stub: parseCell(stub),
    };
});

// Header categories we treat as "pillars" with a real Full/Partial/Stub split.
// The 2026-05-23 table includes meta + native-bridge rows that are 1-of-1 or
// all-Full — keep them so the totals line up, but the component decides which
// to render in the pillar overview vs. the supplementary detail strip.
const out = `// AUTO-GENERATED by website/scripts/generate-coverage.mjs from STATUS.md.
// DO NOT EDIT BY HAND — re-run \`gjsify run generate-coverage\` (or the build
// pre-step) to refresh.
//
// Source: the "Summary" table in STATUS.md (## Summary section). Each entry
// captures the Total / Full / Partial / Stub split for one pillar row.

export interface PillarCoverage {
    /** Category label as it appears in STATUS.md (verbatim). */
    category: string;
    /** Total surveyed entries in this pillar. */
    total: number;
    /** Fully implemented entries. */
    full: number;
    /** Partially implemented entries (core works; specific subsystems open). */
    partial: number;
    /** Stub-only entries (deprecated / browser-irrelevant / no-op). */
    stub: number;
}

export const pillarCoverage: readonly PillarCoverage[] = ${JSON.stringify(pillars, null, 4)};

/** Pillars meaningful as a top-level coverage breakdown — meta + native-bridge
 *  rows are excluded (they aren't multi-entry "categories" that benefit from a
 *  bar). Keeps the visual hierarchy clean. */
export const overviewPillars: readonly PillarCoverage[] = pillarCoverage.filter(
    (p) => !/(meta|native bridges?)$/i.test(p.category),
);

/** Aggregate over the overview-tier pillars (all rendered in the bar grid). */
export function tallyOverview(): {
    total: number; full: number; partial: number; stub: number;
    implementedPct: number;
} {
    const acc = { total: 0, full: 0, partial: 0, stub: 0 };
    for (const p of overviewPillars) {
        acc.total += p.total; acc.full += p.full;
        acc.partial += p.partial; acc.stub += p.stub;
    }
    const implementedPct = acc.total === 0 ? 0
        : Math.round(((acc.full + acc.partial) / acc.total) * 100);
    return { ...acc, implementedPct };
}
`;

writeFileSync(outPath, out, 'utf8');
console.log(`generate-coverage: wrote ${outPath} (${pillars.length} pillars)`);
