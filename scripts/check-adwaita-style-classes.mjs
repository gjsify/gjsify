#!/usr/bin/env node
// The style-class ledger names exactly the classes libadwaita DOCUMENTS.
//
// THE INCIDENT
//
// `style-classes.md` is the public contract for a consumer of any Adwaita
// renderer: put `.card` on a box, `.boxed-list` on a list, `.toolbar` on a bar.
// Twenty-one of those classes had no rule in `@gjsify/adwaita-web` (#1049), and
// nothing could see it — the roadmap tracked "missing partials" by FILENAME, and
// the three sources name their files differently enough that such a diff reports
// gaps that are not gaps and misses gaps that are.
//
// TWO CHECKS, TWO PLACES, AND WHY THEY ARE SPLIT
//
//   1. Does every class in the ledger have a RULE? That is
//      `packages/web/adwaita-web/src/style-classes.spec.ts`, in the browser
//      suite, because the only honest answer comes from the COMPILED stylesheet
//      (two classes lived in comments, three others are generated by an `@each`
//      and appear in no source text at all).
//   2. Does the LEDGER still cover the document? That is this script. It needs
//      `refs/libadwaita`, which the browser suite does not have.
//
// WHY THE SKIP IS LOCAL-ONLY
//
// It used to be unconditional, argued as "the ledger cannot drift on its own, only an
// upstream bump moves it, and an upstream bump happens in a checkout that has the
// submodule". The second half is what fails. An upstream bump lands as a PULL REQUEST,
// and no workflow here passed `submodules:` to actions/checkout, so the CI run of the
// one event this gate exists for skipped along with every other run. Nothing forced a
// local run either: no npm script names this file, no git hook runs it, and `refs-pin`
// covers only the two packages that link a `refs/` submodule by Cargo path dependency.
// From the day it was written until the checkout step landed beside it, this exited 0
// having compared nothing.
//
// So an absent input SKIPS locally, where a contributor with no `refs/` submodule
// realized is the normal case, and FAILS on the runner, where it can only mean the
// checkout step went missing. That is the discriminator — it turns "the checkout quietly
// stopped happening" from invisible into loud.
//
// The discriminator is `GITHUB_ACTIONS`, not `CI`, for two reasons: the step it names
// exists only in a GitHub workflow, and `CI` is set — often to `false` or `0`, both
// truthy as strings — by local runners and agent sandboxes that are running no workflow
// at all. Same spelling `verify-package-outputs.mjs` and its two siblings already use.
//
// Usage: node scripts/check-adwaita-style-classes.mjs [--root <dir>]

import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const rootFlag = args.indexOf('--root');
const ROOT = rootFlag === -1 ? join(dirname(fileURLToPath(import.meta.url)), '..') : args[rootFlag + 1];

const DOC = join(ROOT, 'refs/libadwaita/doc/style-classes.md');
const LEDGER = join(ROOT, 'packages/web/adwaita-web/src/style-classes.spec.ts');

// Named, not reproduced: pasting the step's YAML here would be a second copy of it,
// stale the first time the step is touched — and the reader needs the address, not the
// body.
const CHECKOUT_STEP = '`Check out refs/libadwaita` in .github/workflows/audit-runtimes.yml';

if (!existsSync(DOC)) {
    if (process.env.GITHUB_ACTIONS) {
        console.error(
            `check-adwaita-style-classes: ${relative(ROOT, DOC)} is absent on a GitHub runner, so\n` +
                'the step that checks the submodule out is missing or failed. Passing here would\n' +
                'report a green gate that compared nothing — the state this check spent its whole\n' +
                `life in. Restore the step that precedes it: ${CHECKOUT_STEP}.`,
        );
        process.exit(1);
    }
    console.log(
        `check-adwaita-style-classes: SKIP — ${relative(ROOT, DOC)} is not checked out ` +
            `(git submodule update --init --depth 1 refs/libadwaita).`,
    );
    process.exit(0);
}

/**
 * Every class the document names, in its own backticked spelling.
 *
 * The document writes them as `` `.foo` `` in prose and in headings alike, which
 * is a stabler anchor than the section structure — sections are titled by topic
 * ("Boxed Lists & Cards"), not by class.
 */
// BOTH SPELLINGS. The upstream doc writes most classes in backticks and a handful in
// `<tt>` tags, and reading only the first missed exactly one: `.accent`
// (style-classes.md:368, the colour-utility table), a documented class this gate has
// therefore never held. It IS implemented (`scss/_labels.scss:53`), so nothing was
// broken — but deleting that rule would have stayed green, which is the whole shape
// this script exists against.
const documented = new Set(
    [...readFileSync(DOC, 'utf8').matchAll(/(?:`|<tt>)\.([a-z0-9-]+)(?:`|<\/tt>)/g)].map((match) => match[1]),
);

/** Every key of `DOCUMENTED_STYLE_CLASSES`, quoted or bare. */
const ledgerSource = readFileSync(LEDGER, 'utf8');
const ledgerBody = ledgerSource.slice(
    ledgerSource.indexOf('DOCUMENTED_STYLE_CLASSES'),
    ledgerSource.indexOf('const selectorText'),
);
const ledger = new Set([...ledgerBody.matchAll(/^ {4}'?([a-z][a-z0-9-]*)'?:/gm)].map((match) => match[1]));

if (documented.size === 0 || ledger.size === 0) {
    console.error('check-adwaita-style-classes: parsed nothing — the scan is broken, not the ledger.');
    process.exit(1);
}

const missing = [...documented].filter((name) => !ledger.has(name)).sort();
const stale = [...ledger].filter((name) => !documented.has(name)).sort();

if (missing.length > 0 || stale.length > 0) {
    console.error('check-adwaita-style-classes: the ledger and the upstream document disagree.\n');
    if (missing.length > 0) {
        console.error(`  Documented upstream, absent from the ledger: ${missing.join(', ')}`);
        console.error(
            '    → add an entry. SHIPPED if this renderer has a rule for it, otherwise a reason ' +
                'saying what it would take.\n',
        );
    }
    if (stale.length > 0) {
        console.error(`  In the ledger, no longer documented upstream: ${stale.join(', ')}`);
        console.error('    → upstream dropped or renamed it; drop the entry (and the rule, if it has one).\n');
    }
    console.error(`  Ledger:   ${relative(ROOT, LEDGER)}`);
    console.error(`  Document: ${relative(ROOT, DOC)}`);
    process.exit(1);
}

console.log(
    `check-adwaita-style-classes: ${ledger.size} documented classes, every one in the ledger ` +
        `(${relative(ROOT, LEDGER)}).`,
);
