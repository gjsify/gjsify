// `gjsify site` — render the static landing page of the CURRENT project from its
// AppStream metainfo, or sync the page catalogues. The work lives in
// `@gjsify/site`; this is the entry point into it.
//
// Why a subcommand and not a `gjsify-site` bin: a bin has to name an
// interpreter in its shebang, and that would pick the runtime FOR the user. The
// CLI already runs on whichever runtime it was installed with — gjs after the
// Linux install script, Node after `npm install -g @gjsify/cli` on
// Windows/macOS, bun or deno when installed with those — so taking the entry
// point through the CLI makes the site build inherit that choice instead of
// overriding it. `@gjsify/site` uses GdkPixbuf for its image work, which is
// reachable on all four (natively under gjs, through the `@gjsify/node-gi`
// reverse bridge otherwise).
//
// Dispatch follows `gjsify storybook`: a generated entry importing
// `@gjsify/site` from the CONSUMER's node_modules, bundled `--app gjs|node` and
// run. That keeps `@gjsify/site` (tier 2) out of this tier-1 package's
// dependencies, and it is what lowers the `gi://GdkPixbuf` import to the right
// thing for the runtime in use.
//
// The resolved install directory is passed to the child as `--package-dir`. A
// bundle's `import.meta.url` is the OUTFILE, so the library cannot find its own
// `po/` and `lib/client/` on its own — only the caller still knows.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

import { hostRuntime } from '@gjsify/rolldown-plugin-gjsify/runtime';

import type { Command } from '../types/index.js';
import { resolveNodeGi } from '../utils/run-node.js';

/** `gjs` builds `--app gjs`; `node`/`bun`/`deno` build the same `--app node` bundle. */
type SiteRuntime = 'gjs' | 'node' | 'bun' | 'deno';

interface SiteCliOptions {
    operation: string;
    root?: string;
    out?: string;
    offline: boolean;
    drafts: boolean;
    cache: boolean;
    cacheDir?: string;
    check: boolean;
    package: boolean;
    runtime?: string;
    globals?: string;
}

/** The `@gjsify/site` install reachable from `cwd`, walking the node_modules chain upwards. */
function resolveSitePackage(cwd: string): string | undefined {
    let dir = resolve(cwd);
    for (;;) {
        const candidate = join(dir, 'node_modules', '@gjsify', 'site');
        if (existsSync(join(candidate, 'package.json'))) return candidate;
        const parent = dirname(dir);
        if (parent === dir) return undefined;
        dir = parent;
    }
}

function gjsOnPath(): boolean {
    return spawnSync('gjs', ['--version'], { stdio: 'ignore' }).status === 0;
}

/**
 * The runtime the page is built for. An explicit `--runtime` wins. Otherwise the host runtime —
 * except that a non-gjs host without `@gjsify/node-gi` in the project cannot run the `--app node`
 * bundle (GdkPixbuf is reached through it), so a consumer that only ran
 * `npm i -D @gjsify/site` falls back to gjs when the system has one.
 */
function pickRuntime(requested: string | undefined, cwd: string): SiteRuntime {
    if (requested) return requested as SiteRuntime;
    const host = hostRuntime() as SiteRuntime;
    if (host === 'gjs' || resolveNodeGi(cwd)) return host;
    return gjsOnPath() ? 'gjs' : host;
}

/**
 * The generated entry. Arguments arrive as ARGV rather than baked in, so the cached bundle serves
 * every invocation — flags change far more often than this does.
 *
 * The exit is spelled per runtime on purpose. Under GJS `process.exit` does not halt and loses its
 * code (the `gjsify storybook` measurement), so the gjs entry uses `system.exit`; both read the
 * user arguments from where their own runtime puts them.
 */
function generateEntry(app: 'gjs' | 'node'): string {
    const header = `// Auto-generated by \`gjsify site\` — do not edit by hand.\nimport { runSiteCli } from '@gjsify/site';\n`;
    return app === 'gjs'
        ? `${header}import system from 'system';\n\nsystem.exit(await runSiteCli(system.programArgs));\n`
        : `${header}\nprocess.exit(await runSiteCli(process.argv.slice(2)));\n`;
}

export const siteCommand: Command<unknown, SiteCliOptions> = {
    command: 'site <operation>',
    description:
        "Render this project's static landing page from its AppStream metainfo (downloads, screenshots, " +
        'release notes, support links), or sync the page catalogues.',
    builder: (yargs) =>
        yargs
            .positional('operation', {
                description: 'build — render the pages; i18n — update the page catalogues',
                type: 'string',
                choices: ['build', 'i18n'],
                demandOption: true,
            })
            .option('root', {
                description: 'Repository to read from (default: the working directory)',
                type: 'string',
            })
            .option('out', { description: 'Output directory, emptied first (default: <root>/dist)', type: 'string' })
            .option('offline', { description: 'Skip every network call', type: 'boolean', default: false })
            .option('drafts', {
                description: 'build: include blog posts marked `draft: true`',
                type: 'boolean',
                default: false,
            })
            .option('cache', {
                description: 'Use the one-hour HTTP response cache (--no-cache to ignore it)',
                type: 'boolean',
                default: true,
            })
            .option('cache-dir', {
                description: 'Where the response cache and the image renditions live',
                defaultDescription: '<root>/node_modules/.cache/gjsify-site',
                type: 'string',
            })
            .option('check', {
                description: 'i18n: report what is out of date instead of writing it',
                type: 'boolean',
                default: false,
            })
            .option('package', {
                description: "i18n: sync @gjsify/site's own catalogues instead of this project's",
                type: 'boolean',
                default: false,
            })
            .option('runtime', {
                description:
                    'Runtime to build for and run on: gjs | node | bun | deno (default: the host runtime). ' +
                    'node/bun/deno build the same `--app node` bundle and require @gjsify/node-gi in the project; ' +
                    'without it the default falls back to gjs.',
                type: 'string',
                choices: ['gjs', 'node', 'bun', 'deno'],
                defaultDescription: 'host runtime (gjs on gjs, else node/bun/deno)',
            })
            .option('globals', { description: 'Value for `gjsify build --globals` (default: auto)', type: 'string' }),
    handler: async (args) => {
        const cwd = process.cwd();
        const packageDir = resolveSitePackage(cwd);
        if (!packageDir) {
            console.error(
                'gjsify site: @gjsify/site is not installed in this project.\n\n' +
                    '  The generator ships as its own package so a project only pays for it when it\n' +
                    '  publishes a page. Add it, then run this again:\n\n' +
                    '      npm install --save-dev @gjsify/site',
            );
            return process.exit(1);
        }
        if (!existsSync(join(packageDir, 'lib', 'client', 'site.js'))) {
            console.error(
                `gjsify site: ${packageDir} has no built client bundle (lib/client/site.js).\n` +
                    '  In a source checkout, build the package first: `gjsify workspace site build`.',
            );
            return process.exit(1);
        }

        const runtime = pickRuntime(args.runtime, cwd);
        const app = runtime === 'gjs' ? 'gjs' : 'node';

        const cacheDir = join(cwd, 'node_modules', '.cache', 'gjsify-site');
        mkdirSync(cacheDir, { recursive: true });
        const entryPath = join(cacheDir, `entry.${app}.ts`);
        const outPath = join(cacheDir, `site.${app}.mjs`);
        writeFileSync(entryPath, generateEntry(app));

        const globals = args.globals ?? 'auto';
        if (app === 'gjs') {
            // The consumer installed `@gjsify/site`, not the polyfills `--globals auto` injects
            // (URL, DOMException, streams, …), so those resolve from beside the running CLI.
            const { BuildAction } = await import('../actions/build.js');
            await BuildAction.bundleFileForGjs(entryPath, outPath, {
                globals,
                preserveDefaultExport: false,
                toolchainAnchor: BuildAction.runningCliFile(),
                logLevel: 'silent',
            });
        } else {
            const { runCli } = await import('../cli-app.js');
            await runCli(['build', entryPath, '--app', app, '--globals', globals, '--outfile', outPath]);
        }

        // RESOLVED values, not the raw argv: the child parses its own flags and
        // cannot know where this CLI found the package.
        const forwarded: string[] = [args.operation, '--package-dir', packageDir];
        if (args.root) forwarded.push('--root', resolve(cwd, args.root));
        if (args.out) forwarded.push('--out', resolve(cwd, args.out));
        if (args.offline) forwarded.push('--offline');
        if (args.drafts) forwarded.push('--drafts');
        if (!args.cache) forwarded.push('--no-cache');
        else if (args.cacheDir) forwarded.push('--cache-dir', resolve(cwd, args.cacheDir));
        if (args.check) forwarded.push('--check');
        if (args.package) forwarded.push('--package');

        if (runtime === 'gjs') {
            const { runGjsBundle } = await import('../utils/run-gjs.js');
            await runGjsBundle(outPath, forwarded, { completion: 'exit', exitOnSuccess: true });
            return;
        }
        if (runtime === 'node') {
            const { runNodeBundle } = await import('../utils/run-node.js');
            await runNodeBundle(outPath, forwarded, { completion: 'exit', exitOnSuccess: true });
            return;
        }
        const { runRuntimeBundle } = await import('../utils/run-node.js');
        await runRuntimeBundle(runtime, outPath, forwarded, { completion: 'exit', exitOnSuccess: true });
    },
};
