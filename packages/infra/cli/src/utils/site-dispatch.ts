// Shared by `gjsify site` and `gjsify webext listing`: both run `runSiteCli` from the CONSUMER's
// `@gjsify/site`, bundled for the runtime the CLI itself is on (see `commands/site.ts` for why).

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

import { hostRuntime } from '@gjsify/rolldown-plugin-gjsify/runtime';

import { resolveNodeGi } from './run-node.js';

/** `gjs` builds `--app gjs`; `node`/`bun`/`deno` build the same `--app node` bundle. */
export type SiteRuntime = 'gjs' | 'node' | 'bun' | 'deno';

/** The `@gjsify/site` install reachable from `cwd`, walking the node_modules chain upwards. */
export function resolveSitePackage(cwd: string): string | undefined {
    let dir = resolve(cwd);
    for (;;) {
        const candidate = join(dir, 'node_modules', '@gjsify', 'site');
        if (existsSync(join(candidate, 'package.json'))) return candidate;
        const parent = dirname(dir);
        if (parent === dir) return undefined;
        dir = parent;
    }
}

export function gjsOnPath(): boolean {
    return spawnSync('gjs', ['--version'], { stdio: 'ignore' }).status === 0;
}

/**
 * The runtime the page is built for. An explicit `--runtime` wins. Otherwise the host runtime —
 * except that a non-gjs host without `@gjsify/node-gi` in the project cannot run the `--app node`
 * bundle (GdkPixbuf is reached through it), so a consumer that only ran
 * `npm i -D @gjsify/site` falls back to gjs when the system has one.
 */
export function pickRuntime(requested: string | undefined, cwd: string): SiteRuntime {
    if (requested) return requested as SiteRuntime;
    const host = hostRuntime() as SiteRuntime;
    if (host === 'gjs' || resolveNodeGi(cwd)) return host;
    return gjsOnPath() ? 'gjs' : host;
}

/**
 * The generated entry. Arguments arrive as ARGV rather than baked in, so the cached bundle serves
 * every invocation — flags change far more often than this does.
 *
 * The exit is spelled per runtime on purpose. Under GJS `process.exit` does not halt and loses its
 * code (the `gjsify storybook` measurement), so the gjs entry uses `system.exit`; both read the
 * user arguments from where their own runtime puts them.
 */
export function generateEntry(app: 'gjs' | 'node', command = 'gjsify site'): string {
    const header = `// Auto-generated by \`${command}\` — do not edit by hand.\nimport { runSiteCli } from '@gjsify/site';\n`;
    return app === 'gjs'
        ? `${header}import system from 'system';\n\nsystem.exit(await runSiteCli(system.programArgs));\n`
        : `${header}\nprocess.exit(await runSiteCli(process.argv.slice(2)));\n`;
}

export interface SiteDispatch {
    /** What the generated entry's header names as its author. */
    invokedAs: string;
    /** Forwarded to `runSiteCli` after `--package-dir`. */
    argv: string[];
    runtime?: string;
    globals?: string;
    /** Whether `lib/client/site.js` must exist (only the page build ships it to the browser). */
    needsClient: boolean;
}

/** Resolves `@gjsify/site`, bundles the entry for the chosen runtime, and runs it; exits the process. */
export async function dispatchSite(options: SiteDispatch): Promise<void> {
    const cwd = process.cwd();
    const packageDir = resolveSitePackage(cwd);
    if (!packageDir) {
        console.error(
            `${options.invokedAs}: @gjsify/site is not installed in this project.\n\n` +
                '  The generator ships as its own package so a project only pays for it when it\n' +
                '  publishes a page or a store listing. Add it, then run this again:\n\n' +
                '      npm install --save-dev @gjsify/site',
        );
        return process.exit(1);
    }
    if (options.needsClient && !existsSync(join(packageDir, 'lib', 'client', 'site.js'))) {
        console.error(
            `${options.invokedAs}: ${packageDir} has no built client bundle (lib/client/site.js).\n` +
                '  In a source checkout, build the package first: `gjsify workspace site build`.',
        );
        return process.exit(1);
    }

    const runtime = pickRuntime(options.runtime, cwd);
    const app = runtime === 'gjs' ? 'gjs' : 'node';

    const cacheDir = join(cwd, 'node_modules', '.cache', 'gjsify-site');
    mkdirSync(cacheDir, { recursive: true });
    const entryPath = join(cacheDir, `entry.${app}.ts`);
    const outPath = join(cacheDir, `site.${app}.mjs`);
    writeFileSync(entryPath, generateEntry(app, options.invokedAs));

    const globals = options.globals ?? 'auto';
    if (app === 'gjs') {
        // The consumer installed `@gjsify/site`, not the polyfills `--globals auto` injects
        // (URL, DOMException, streams, …), so those resolve from beside the running CLI.
        const { BuildAction } = await import('../actions/build.js');
        await BuildAction.bundleFileForGjs(entryPath, outPath, {
            globals,
            preserveDefaultExport: false,
            toolchainAnchor: BuildAction.runningCliFile(),
            logLevel: 'silent',
        });
    } else {
        const { runCli } = await import('../cli-app.js');
        await runCli(['build', entryPath, '--app', app, '--globals', globals, '--outfile', outPath]);
    }

    const forwarded = [...options.argv.slice(0, 1), '--package-dir', packageDir, ...options.argv.slice(1)];
    if (runtime === 'gjs') {
        const { runGjsBundle } = await import('./run-gjs.js');
        await runGjsBundle(outPath, forwarded, { completion: 'exit', exitOnSuccess: true });
        return;
    }
    if (runtime === 'node') {
        const { runNodeBundle } = await import('./run-node.js');
        await runNodeBundle(outPath, forwarded, { completion: 'exit', exitOnSuccess: true });
        return;
    }
    const { runRuntimeBundle } = await import('./run-node.js');
    await runRuntimeBundle(runtime, outPath, forwarded, { completion: 'exit', exitOnSuccess: true });
}
