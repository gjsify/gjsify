#!/usr/bin/env bash
# Rebuilds the GResource fixtures of src/gio-resource.*spec.ts from the sources in this directory.
# Needs glib-compile-resources (GLib 2.88.3 wrote the committed bytes); CI does not run it.
set -euo pipefail
cd "$(dirname "$0")"
glib-compile-resources --sourcedir=data --target=fixture.gresource fixture.gresource.xml
glib-compile-resources --sourcedir=overlay --target=overlay.gresource overlay.gresource.xml
{
    echo '// GENERATED by fixtures/gio-resource/build.sh from the .gresource files next to it. Do not edit.'
    echo '// The bytes `glib-compile-resources` wrote, as base64, so every runtime reads the same fixture.'
    for name in fixture overlay; do
        printf 'export const %s_GRESOURCE_BASE64 =\n    %s;\n' "${name^^}" "'$(base64 -w0 "$name.gresource")'"
    done
} > ../../src/gio-resource.fixtures.ts
