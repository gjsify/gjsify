/**
 * The two Cherokee case-folding ranges, which fold lowercase UP to uppercase —
 * the reverse of every other script, and the reason `toLowerCase()` alone
 * cannot be a case fold even for single-character mappings.
 *
 * `CaseFolding.txt`: `AB70..ABBF; C; 13A0..13EF` and `13F8..13FD; C; 13F0..13F5`.
 */
function foldCherokee(codePoint: number): string | undefined {
    if (codePoint >= 0xab70 && codePoint <= 0xabbf) return String.fromCodePoint(codePoint - 0xab70 + 0x13a0);
    if (codePoint >= 0x13f8 && codePoint <= 0x13fd) return String.fromCodePoint(codePoint - 8);
    return undefined;
}

/**
 * `g_utf8_casefold` — Unicode FULL case folding, i.e. `toLowerCase()` plus the mappings
 * where a case fold and a lowercase mapping disagree. The obvious implementation ships
 * wrong behaviour in languages people actually use, invisibly to an ASCII test suite;
 * the three canaries, verified against a real full-folding implementation:
 *
 * | input | `toLowerCase()` | case fold |
 * |----------|-----------------|------------|
 * | `Straße` | `straße` | `strasse` |
 * | `ΟΔΟΣ` | `οδος` | `οδοσ` |
 * | `ﬁle` | `ﬁle` | `file` |
 *
 * `normalize('NFKC').toLowerCase` is NOT a substitute: it repairs the
 * ligature, still misses `ß` and final sigma, and OVER-normalises `Ǆ` (U+01C4)
 * to the two-character `dž` where a case fold gives the single character `ǆ`.
 */
export const defaultCaseFolder: CaseFolder = (text: string): string => {
    let folded = '';
    for (const character of text.toLowerCase()) {
        const codePoint = character.codePointAt(0)!;
        // Latin-1 and below can never be Cherokee, and only two characters in it
        // are in the table — worth the branch, this runs on every keystroke.
        if (codePoint < 0xb5) {
            folded += character;
            continue;
        }
        folded += CASEFOLD_EXTRAS.get(character) ?? foldCherokee(codePoint) ?? character;
    }
    return folded;
};

/** Per-row flags `make_comparable` reads off the row it is comparing. */
export interface MakeComparableOptions {
    /** `AdwPreferencesRow:use-markup`. Defaults to `true`, as the property does. */
    useMarkup?: boolean;
    /** `AdwPreferencesRow:use-underline`. Defaults to `false`, as the property does. */
    useUnderline?: boolean;
    /**
     * `make_comparable`'s third argument. The TITLE path passes `true`, the
     * SUBTITLE path passes `false` — so a
     * subtitle keeps its underscores even on a row that uses mnemonics.
     */
    allowUnderline?: boolean;
}

/**
 * `make_comparable`: the form of a string the search compares against — case-folded,
 * markup-stripped and (for titles on mnemonic rows) mnemonic-stripped.
 *
 * THE ORDER IS NOT THE OBVIOUS ONE: fold FIRST, parse the FOLDED string second, as the C
 * does. The two differ for any markup whose tag name is case-sensitive to the parser;
 * folding a lowercase-only tag set leaves it parseable, which is why `<b>Dark</b> Style`
 * still reduces to `dark style` rather than keeping its tags.
 */
export function makeComparable(
    source: string | null | undefined,
    options: MakeComparableOptions = {},
    fold: CaseFolder = defaultCaseFolder,
): string {
    let plaintext = fold(source ?? '');

    if (options.useMarkup ?? true) {
        // A failed parse keeps the folded text — the C logs a g_critical and
        // carries on, so the row stays searchable under its literal spelling.
        plaintext = stripMarkup(plaintext) ?? plaintext;
    }

    if ((options.allowUnderline ?? true) && (options.useUnderline ?? false)) {
        plaintext = stripMnemonic(plaintext);
    }

    return plaintext;
}

// Group header derivation

/** What {@link derivePreferencesGroupHeader} is asked about. */
export interface PreferencesGroupHeaderInput {
    /**
     * `AdwPreferencesGroup:title`. `null`/`undefined` is the empty string —
     * `adw_preferences_group_set_title` normalises NULL to `""`.
     */
    title?: string | null;
    /**
     * `AdwPreferencesGroup:description`. Normalised here as well, although
     * `adw_preferences_group_set_description` passes NULL straight through
     * where its own `set_title` and `adw_preferences_page_set_title`
     * both normalise — an inconsistency in the C
     * with no behavioural consequence, since the visibility test treats NULL and
     * `""` alike.
     */
    description?: string | null;
    /** Whether an `AdwPreferencesGroup:header-suffix` widget is set. */
    hasHeaderSuffix?: boolean;
    /**
     * How many children the listbox holds. This is the RAW child count —
     * `update_listbox_visibility` reads `gtk_widget_observe_children (listbox)`,
     * NOT the title-filtered model that
     * `get_rows` builds, so a row with an empty title still keeps the card
     * painted.
     */
    rowCount?: number;
    /**
     * Whether the title/description labels interpret Pango markup. `true` by
     * default because both labels are `use-markup=True` in
     * adw-preferences-group.ui — a renderer that shows the strings verbatim
     * passes `false`.
     */
    useMarkup?: boolean;
}

/** The five derived visual states of a preferences group. */
export interface PreferencesGroupHeaderState {
    /** `update_title_visibility`. */
    titleVisible: boolean;
    /** `update_description_visibility`. */
    descriptionVisible: boolean;
    /** `update_header_visibility` — the header box takes no space otherwise. */
    headerVisible: boolean;
    /**
     * `is_single_line`, carried as the `single-line` style class.
     * Load-bearing: the stylesheet gives a single-line header `min-height: 34px`
     * and a multi-line one `margin-bottom: 6px`
     * (stylesheet/widgets/_preferences.scss).
     */
    singleLine: boolean;
    /** `update_listbox_visibility` — the `.boxed-list` card is hidden at zero rows. */
    listboxVisible: boolean;
}

/**
 * The text a `use-markup` label DISPLAYS, which is what the visibility tests
 * read: `update_title_visibility` compares `gtk_label_get_text` — markup already
 * stripped — while `adw_preferences_group_get_title` returns
 * `gtk_label_get_label`, the raw markup (adw-preferences-group.c vs:485).
 *
 * So a title of `<b></b>` reads back as `<b></b>` and is HIDDEN. Unparseable
 * markup keeps the raw string, which is both the safe direction and what a
 * renderer that paints the string verbatim shows.
 */
function displayedLabelText(value: string | null | undefined, useMarkup: boolean): string {
    const raw = value ?? '';
    if (!useMarkup) return raw;
    return stripMarkup(raw) ?? raw;
}

/**
 * The five header/listbox states of an `Adw.PreferencesGroup`, derived once for
 * every renderer.
 *
 * A pure derivation rather than a state machine, which is the honest shape: C
 * recomputes all of this from scratch in `update_*_visibility` on every change,
 * holding no state of its own beyond the widgets it is reading.
 *
 * Only the EXACT empty string hides a label — `g_strcmp0 (text, "")`, so a title
 * of a single space is a visible title and must not be trimmed. That is the same
 * rule {@link stringIsNotEmpty} carries for the label bindings, so it is applied
 * from there rather than respelled here; what stays local is only which STRING it
 * is applied to, since this widget judges the markup-stripped display text.
 */
export function derivePreferencesGroupHeader(input: PreferencesGroupHeaderInput): PreferencesGroupHeaderState {
    const useMarkup = input.useMarkup ?? true;
    const titleVisible = stringIsNotEmpty(displayedLabelText(input.title, useMarkup));
    const descriptionVisible = stringIsNotEmpty(displayedLabelText(input.description, useMarkup));
    const hasHeaderSuffix = input.hasHeaderSuffix ?? false;

    return {
        titleVisible,
        descriptionVisible,
        headerVisible: titleVisible || descriptionVisible || hasHeaderSuffix,
        // A description forces two lines; otherwise a suffix OR a title is one.
        singleLine: !descriptionVisible && (hasHeaderSuffix || titleVisible),
        listboxVisible: (input.rowCount ?? 0) > 0,
    };
}

// The search corpus

/**
 * One indexable row, as the search reasons about it.
 *
 * `isActionRow` is load-bearing and is NOT "has a subtitle": only
 * `ADW_IS_ACTION_ROW` rows have their subtitle searched,
 * and `AdwEntryRow` derives from
 * `AdwPreferencesRow`, not from `AdwActionRow` — so the
 * text typed into an entry row is deliberately not searchable. Same for
 * `AdwExpanderRow` and `AdwButtonRow`.
 */
export interface PreferencesSearchRow<T = unknown> {
    /** `AdwPreferencesRow:title`. A row with an empty title is not indexed at all. */
    title: string;
    /** `AdwActionRow:subtitle`, consulted only when `isActionRow`. */
    subtitle?: string | null;
    /** `AdwPreferencesRow:use-markup`, default `true`. */
    useMarkup?: boolean;
    /** `AdwPreferencesRow:use-underline`, default `false`. */
    useUnderline?: boolean;
    /** `gtk_widget_get_visible`, default `true`. A hidden row leaves the corpus. */
    visible?: boolean;
    /** Whether the row derives from `AdwActionRow`, default `false`. */
    isActionRow?: boolean;
    /** The renderer's own row object, carried through to the result untouched. */
    ref?: T;
}

/** One group of rows, as the search reasons about it. */
export interface PreferencesSearchGroup<T = unknown> {
    /** `AdwPreferencesGroup:title`; an empty one drops out of the result subtitle. */
    title?: string | null;
    /** `is_visible_group`, default `true`. */
    visible?: boolean;
    /** The group's preferences rows, in listbox order. */
    rows: readonly PreferencesSearchRow<T>[];
    /** The renderer's own group object. */
    ref?: T;
}

/**
 * One page, as the search reasons about it.
 *
 * `visible` is the same flag `ViewStackState.setPageVisible` maintains —
 * the dialog's pages ARE an `AdwViewStack`,
 * so a renderer holds the page ORDER and SELECTION there and describes the
 * same pages here for indexing.
 */
export interface PreferencesSearchPage<T = unknown> {
    /** `AdwPreferencesPage:name`, the view stack child name. */
    name?: string | null;
    /** `AdwPreferencesPage:title`; shown in a result subtitle when several pages are visible. */
    title?: string;
    /** `AdwPreferencesPage:icon-name`. Not read by the search; carried for the switcher. */
    iconName?: string | null;
    /** `AdwPreferencesPage:use-underline`, default `false`. */
    useUnderline?: boolean;
    /** `AdwViewStackPage:visible`, default `true`. An invisible page contributes nothing. */
    visible?: boolean;
    /** `AdwPreferencesPage:description`. Not searched — only rows are. */
    description?: string;
    /** The page's groups, in order. */
    groups: readonly PreferencesSearchGroup<T>[];
    /** The renderer's own page object. */
    ref?: T;
}

/** One row of the corpus, with the ancestors a result subtitle needs. */
export interface PreferencesSearchEntry<T = unknown> {
    page: PreferencesSearchPage<T>;
    group: PreferencesSearchGroup<T>;
    row: PreferencesSearchRow<T>;
}

/**
 * `get_n_pages` — how many pages are visible,
 * which is what decides whether a result subtitle names its page.
 */
export function countVisiblePages<T>(pages: readonly PreferencesSearchPage<T>[]): number {
    let count = 0;
    for (const page of pages) if (page.visible !== false) count += 1;
    return count;
}

/**
 * The search corpus: every row the dialog will ever match against.
 *
 * This is the filter → map → flatten chain of `adw_preferences_dialog_init`
 * composed with `adw_preferences_page_get_rows` and
 * `adw_preferences_group_get_rows`, i.e. THREE filters written in
 * three different C files:
 *
 * 1. visible PAGES only — a `GtkBoolFilter` over `AdwViewStackPage:visible`;
 * 2. visible GROUPS only — `is_visible_group`;
 * 3. rows that are preferences rows AND visible AND have a NON-EMPTY title —
 * `row_has_title`.
 *
 * Filter 3 is the one a port drops, and dropping it is invisible: nothing
 * errors, the search just silently indexes rows a user cannot recognise (an
 * untitled separator row) or, with the visibility half missing, rows that are
 * not on screen. The `ADW_IS_PREFERENCES_ROW` half of it is expressed
 * statically here — a `PreferencesSearchRow[]` cannot hold a plain list-box row.
 */
export function collectSearchRows<T>(pages: readonly PreferencesSearchPage<T>[]): PreferencesSearchEntry<T>[] {
    const entries: PreferencesSearchEntry<T>[] = [];

    for (const page of pages) {
        if (page.visible === false) continue;
        for (const group of page.groups) {
            if (group.visible === false) continue;
            for (const row of group.rows) {
                if (row.visible === false) continue;
                if (row.title === '') continue;
                entries.push({ page, group, row });
            }
        }
    }

    return entries;
}

/**
 * `filter_search_results`: whether a row
 * matches the current search terms.
 *
 * Three properties a port tends to get wrong, all of them user-visible:
 *
 * - it is a SUBSTRING test (`strstr`), not a prefix and not word-boundary —
 * `ARK` matches `Dark Style`;
 * - the EMPTY query matches everything (`strstr (title, "")` returns `title`),
 * which is why the dialog shows "results" and not "no results" before the
 * user has typed anything;
 * - the query is only case-FOLDED. It is not markup-parsed and not
 * mnemonic-stripped, so typing `_` searches for a literal underscore.
 */
export function rowMatchesQuery<T>(
    row: PreferencesSearchRow<T>,
    query: string,
    fold: CaseFolder = defaultCaseFolder,
): boolean {
    const terms = fold(query ?? '');
    const flags = { useMarkup: row.useMarkup, useUnderline: row.useUnderline };

    if (makeComparable(row.title, { ...flags, allowUnderline: true }, fold).includes(terms)) return true;
    if (!row.isActionRow) return false;

    return makeComparable(row.subtitle, { ...flags, allowUnderline: false }, fold).includes(terms);
}

/**
 * The translated fallback for a page with no title.
 * Exported so a renderer with a translation
 * catalogue can pass its own through `untitledPageLabel`.
 */
export const UNTITLED_PAGE_LABEL = 'Untitled page';

/** The `page → group` separator: U+2192, one space either side. */
const SUBTITLE_ARROW = '→';

/** What {@link createSearchRowSubtitle} needs about a matched row's ancestors. */
export interface SearchRowSubtitleInput {
    /** The group's title. `''` counts as absent. */
    groupTitle?: string | null;
    /**
     * The page's title. `undefined` means there is no page ancestor at all —
     * unreachable through the public API, since a row always sits in a page.
     */
    pageTitle?: string | null;
    /** `AdwPreferencesPage:use-underline` — decides whether the page title is mnemonic-stripped. */
    pageUseUnderline?: boolean;
    /** The matched ROW's `use-markup` — decides whether the page title is markup-escaped. Default `true`. */
    rowUseMarkup?: boolean;
    /** `get_n_pages` — the page is only named when more than one page is visible. */
    nVisiblePages: number;
    /** Override for {@link UNTITLED_PAGE_LABEL}. */
    untitledPageLabel?: string;
}

/**
 * `create_search_row_subtitle` — the second
 * line of a search result, e.g. `General → Appearance`.
 *
 * The rules, in the order the C applies them, none of them symmetric:
 *
 * - an empty GROUP title becomes "absent", and the whole `page → group` join
 * is then skipped — the result falls through to the bare page title;
 * - the PAGE title is mnemonic-stripped when the PAGE uses underline, then
 * markup-escaped when the ROW uses markup (a page-level property and a
 * row-level property deciding two steps on the same string), and only then
 * tested for emptiness;
 * - the join happens only when more than one page is VISIBLE; with a single
 * page the subtitle is the group title alone;
 * - the group title is NOT escaped, so the two halves of `page → group` are
 * escaped differently on purpose.
 *
 * `null` means "no subtitle at all", which is what a renderer should render as
 * an absent line rather than as an empty one.
 */
export function createSearchRowSubtitle(input: SearchRowSubtitleInput): string | null {
    let groupTitle: string | null = input.groupTitle ?? null;
    if (groupTitle === '') groupTitle = null;

    let pageTitle: string | null = null;
    if (input.pageTitle !== undefined && input.pageTitle !== null) {
        pageTitle = input.pageUseUnderline ? stripMnemonic(input.pageTitle) : input.pageTitle;
        if (input.rowUseMarkup ?? true) pageTitle = escapeMarkup(pageTitle);
        if (pageTitle === '') pageTitle = null;
    }

    if (groupTitle === null) return pageTitle;
    if (input.nVisiblePages <= 1) return groupTitle;

    const effectivePageTitle = pageTitle ?? input.untitledPageLabel ?? UNTITLED_PAGE_LABEL;
    return `${effectivePageTitle} ${SUBTITLE_ARROW} ${groupTitle}`;
}

/** One row of the search results list. */
export interface PreferencesSearchResult<T = unknown> {
    /** Copied verbatim from the matched row (`new_search_row_for_preference`). */
    title: string;
    /** {@link createSearchRowSubtitle}; `null` when there is nothing to show. */
    subtitle: string | null;
    /** The matched row's `use-markup`, copied onto the result row. */
    useMarkup: boolean;
    /** The matched row's `use-underline`, copied onto the result row. */
    useUnderline: boolean;
    /** The page the row lives on — what `search_result_activated_cb` switches to. */
    page: PreferencesSearchPage<T>;
    /** The group the row lives in. */
    group: PreferencesSearchGroup<T>;
    /** The matched row — what `search_result_activated_cb` focuses. */
    row: PreferencesSearchRow<T>;
}

/** Knobs for {@link searchPreferences}. */
export interface SearchPreferencesOptions {
    /** Case folder to compare with. Defaults to {@link defaultCaseFolder}. */
    fold?: CaseFolder;
    /** Translated replacement for {@link UNTITLED_PAGE_LABEL}. */
    untitledPageLabel?: string;
}

/**
 * The whole search half in one call: corpus → filter → result rows, in corpus
 * order (which is page order, then group order, then row order — the same order
 * `GtkFlattenListModel` produces).
 *
 * Each result carries the source `page`/`group`/`row` so a renderer can
 * implement `search_result_activated_cb` —
 * switch the visible page, focus the row — without re-deriving anything.
 */
export function searchPreferences<T>(
    pages: readonly PreferencesSearchPage<T>[],
    query: string,
    options: SearchPreferencesOptions = {},
): PreferencesSearchResult<T>[] {
    const fold = options.fold ?? defaultCaseFolder;
    const nVisiblePages = countVisiblePages(pages);
    const results: PreferencesSearchResult<T>[] = [];

    for (const { page, group, row } of collectSearchRows(pages)) {
        if (!rowMatchesQuery(row, query, fold)) continue;

        results.push({
            title: row.title,
            subtitle: createSearchRowSubtitle({
                groupTitle: group.title,
                // A row always has a page ancestor, so an absent title is an
                // EMPTY one, not a missing page.
                pageTitle: page.title ?? '',
                pageUseUnderline: page.useUnderline,
                rowUseMarkup: row.useMarkup,
                nVisiblePages,
                untitledPageLabel: options.untitledPageLabel,
            }),
            useMarkup: row.useMarkup ?? true,
            useUnderline: row.useUnderline ?? false,
            page,
            group,
            row,
        });
    }

    return results;
}

