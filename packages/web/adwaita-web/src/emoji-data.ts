/** The section ids in order, `recent` FIRST — the struct order of `GtkEmojiChooser`. */
export const EMOJI_SECTION_IDS: readonly string[] = ['recent', ...EMOJI_CATEGORIES.map((c) => c.id)];

/** The heading of a section, `''` for `recent` — the one with no heading widget at all. */
export function emojiHeading(id: string): string {
    return EMOJI_CATEGORIES.find((category) => category.id === id)?.heading ?? '';
}

/** The toolbar button's tooltip for a section: its heading, or `Recent` for the first. */
export function emojiTooltip(id: string): string {
    return id === 'recent' ? 'Recent' : (EMOJI_CATEGORIES.find((category) => category.id === id)?.tooltip ?? '');
}
