// The emoji a `<gtk-emoji-chooser>` shows, and the words it searches.
//
// WHY THIS TABLE IS SMALL, AND WHAT IT IS NOT
//
// `GtkEmojiChooser` loads its emoji from `/org/gtk/libgtk/emoji/<lang>.data`, a
// COMPILED GVariant resource of about 1.2 MB per language, read at runtime through
// `g_resources_lookup_data` (gtkemojichooser.c:648-680). It carries, per emoji, the code
// points (a 0 stands for the variation selector or the skin-tone modifier), the English
// name, the localised name and two keyword lists — and the search matches the NAMES AND
// KEYWORDS, never the glyph (gtkemojichooser.c:896-958). Nothing in a browser can read
// that blob: it is a GVariant serialisation, and shipping it would mean shipping GTK's
// compiled resource.
//
// So the replica carries a curated table with the same SHAPE — code points, name,
// keywords — in GTK's own ten sections with GTK's own headings, and says so where it is
// visible: the `emoji-picked` signal carries the same Unicode sequence, the search
// matches the same token lists with the same prefix rule, and the sections are the
// struct order of `GtkEmojiChooser`. Every derivation that READS this file lives in the
// element; nothing here decides anything.
//
// SECTION ORDER is the struct order (gtkemojichooser.c:216-228) and the order
// `setup_section` registers them in (gtkemojichooser.c:1075-1085): recent first, then
// the nine categories by ascending group (people 0, body 1, nature 3, food 4, travel 5,
// activities 6, objects 7, symbols 8, flags 9 — group 2 is absent upstream). The
// HEADINGS are the `.ui` labels with their `emoji category` context, mnemonics absent
// because the `.ui` headings have none: "Smileys & People", "Body & Clothing",
// "Animals & Nature", "Food & Drink", "Travel & Places", "Activities", "Objects",
// "Symbols", "Flags".

/** One emoji entry: the code points and the words the search reads. */
export interface EmojiEntry {
    /** The code points, as one string — a ZWJ sequence is already spelled out. */
    readonly text: string;
    /** The English name — `filter_func`'s second list. */
    readonly name: string;
    /** Search keywords, one word each — `filter_func`'s third list. */
    readonly keywords: readonly string[];
}

/** One `EmojiSection`, with the heading and the toolbar button's own label. */
export interface EmojiCategory {
    /** The section key: `recent`, `people`, … */
    readonly id: string;
    /** The heading above the section, `''` for the one without (recent). */
    readonly heading: string;
    /** The `.ui` tooltip of the toolbar button, which for every section but recent is its heading. */
    readonly tooltip: string;
    /** The emoji, in the order GTK appends them. */
    readonly entries: readonly EmojiEntry[];
}

/** One table row. Keywords are space-separated because `match_tokens` prefixes per WORD. */
function row(text: string, name: string, keywords = ''): EmojiEntry {
    return { text, name, keywords: keywords === '' ? [] : keywords.split(' ') };
}

/** `MAX_RECENT` — 7 columns by 3 rows (gtkemojichooser.c:363). */
export const EMOJI_MAX_RECENT = 7 * 3;

/** `EMOJI_SKIN_TONES` — `1F3FB`…`1F3FF`, the five modifiers (gtkemojichooser.c:530). */
export const EMOJI_SKIN_TONES: readonly string[] = ['\u{1F3FB}', '\u{1F3FC}', '\u{1F3FD}', '\u{1F3FE}', '\u{1F3FF}'];

/** `has_variations` (gtkemojichooser.c:489-508) — whether an entry carries a skin slot. */
export function hasVariations(entry: EmojiEntry): boolean {
    return [...entry.text].some((character) => EMOJI_SKIN_TONES.includes(character));
}

