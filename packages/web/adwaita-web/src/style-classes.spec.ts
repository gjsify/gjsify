/**
 * Selector text of every rule in the stylesheet, with `:not(…)` removed.
 *
 * Matching against selectors rather than the whole file keeps a class name in a
 * comment or in a `content:` string from counting as a rule.
 */
const selectorText = (css: string): string =>
    [...css.matchAll(/(?:^|\}|\*\/)([^{}]+)\{/g)].map((match) => match[1].replace(/:not\([^)]*\)/g, '')).join('\n');

const definesClass = (selectors: string, name: string): boolean =>
    new RegExp(`\\.${name.replace(/-/g, '\\-')}(?![-\\w])`).test(selectors);

export const AdwStyleClassesTest = async () => {
    await describe('documented style classes', async () => {
        const selectors = selectorText(ADWAITA_WEB_CSS);

        await it('ships a rule for every class libadwaita documents', async () => {
            const missing = Object.entries(DOCUMENTED_STYLE_CLASSES)
                .filter(([, entry]) => entry.shipped)
                .map(([name]) => name)
                .filter((name) => !definesClass(selectors, name));

            // Named in the failure so the message says WHICH contract broke.
            expect(missing.join(', ')).toBe('');
        });

        await it('keeps the ledger honest about the ones it does not ship', async () => {
            // The reverse direction: a class that quietly gained a rule must move
            // to SHIPPED, or the reason next to it is now a lie. Every non-shipped
            // entry also has to carry that reason.
            const unexpected = Object.entries(DOCUMENTED_STYLE_CLASSES)
                .filter(([, entry]) => !entry.shipped)
                .filter(([name, entry]) => definesClass(selectors, name) || !entry.reason)
                .map(([name]) => name);

            expect(unexpected.join(', ')).toBe('');
        });

        await it('is a real stylesheet and not an empty string', async () => {
            // The two assertions above both pass vacuously against an empty CSS
            // bundle — a stale or unbuilt `styles.generated.ts` would read as a
            // clean bill of health.
            expect(selectors.length > 10_000).toBe(true);
        });
    });
};
