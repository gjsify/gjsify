// libadwaita's DOCUMENTED style-class surface, held against the compiled
// stylesheet.
//
// THE INCIDENT
//
// `refs/libadwaita/doc/style-classes.md` is the contract an app author reads:
// `.card` on a box, `.boxed-list` on a list, `.toolbar` on a bar, `.linked`
// around a button group. Twenty-one of those classes had no rule in this package
// at all (#1049) — a consumer following the upstream documentation got nothing,
// silently.
//
// WHY THIS READS THE COMPILED CSS AND NOT THE SCSS
//
// A source grep cannot answer the question, and got it wrong in both directions:
//
//   - `.osd` and `.linked` appeared in `scss/` only inside COMMENTS, so a text
//     search reported them as present while the code spelled its own
//     `.adw-linked` and shipped no `.osd` at all.
//   - `.error` / `.warning` / `.success` are generated by an `@each` in
//     `_labels.scss` (`.#{$e_type}`), so they appear in no source text at all and
//     a text search reports them missing.
//
// The compiled stylesheet is what a consumer actually loads, so that is what is
// asserted. `:not(…)` is stripped before matching, because a selector mentioning
// a class in order to EXCLUDE it (`.toolbar … :not(.opaque)`) is the opposite of
// shipping it.
//
// THE LEDGER IS THE POINT
//
// Every documented class has an entry, and a class that is NOT shipped must say
// why — so the next reader sees the difference between "we decided against it"
// and "nobody noticed". `scripts/check-adwaita-style-classes.mjs` holds this
// ledger against the upstream document itself, so a libadwaita bump that adds a
// class cannot leave the ledger silently short.
//
// Reference: refs/libadwaita/doc/style-classes.md
import { describe, expect, it } from '@gjsify/unit';

import { ADWAITA_WEB_CSS } from './styles.generated.js';

/** Ships a rule in the compiled stylesheet. */
const SHIPPED = { shipped: true } as const;

/** Deprecated upstream, with a named replacement — deliberately not ported. */
const deprecated = (replacement: string) =>
    ({ shipped: false, reason: `deprecated upstream — use ${replacement}` }) as const;

/** No counterpart in this renderer (yet), with the reason. */
const unported = (reason: string) => ({ shipped: false, reason }) as const;

