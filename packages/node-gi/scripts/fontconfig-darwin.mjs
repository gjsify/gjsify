// The fontconfig CONFIG the darwin bundle ships — the other half of `bundle-fonts.mjs`.
//
// WHAT WAS MEASURED, in a published `.app` on macOS 27 / M4, launched under a sandbox that
// denies every read below /opt/homebrew and /usr/local:
//
//   stderr:  Fontconfig error: Cannot load default config file: File not found
//   lsof:    AdwaitaMono-{Regular,Bold}.ttf, Helvetica.ttc, Menlo.ttc … and NOT ONE
//            AdwaitaSans-*.ttf, although `gtk/share/fonts/adwaita` carried them
//   window:  body text and buttons in Adwaita MONO, the heading in a system face
//
// Two independent causes, both invisible on a Homebrew build host:
//
//   1. NOTHING SHIPPED A CONFIG. `gtk-runtime.js` only sets `FONTCONFIG_FILE` when
//      `<bundle>/etc/fonts/fonts.conf` exists, and the darwin bundle has never had one. The
//      bundled libfontconfig then falls back to the prefix compiled into it, which on the
//      build host is Homebrew's `/opt/homebrew/etc/fonts`. Off that host there is no config
//      at all: no `<dir>` entries beyond the built-in defaults, so the bundle's own
//      `share/fonts` was never scanned.
//
//   2. `gtk-font-name` NAMES A FAMILY ONLY CORETEXT KNOWS. GTK's macOS backend sets it to
//      `.AppleSystemUIFont 12`, which is a CoreText alias, not a fontconfig family. The
//      loader forces `PANGOCAIRO_BACKEND=fc` (measured: Tamil renders with `fc`, is TOFU on
//      the platform map), so fontconfig is asked to resolve `.AppleSystemUIFont`, finds no
//      family of that name, and substitutes — arbitrarily, and differently depending on what
//      else is installed (Adwaita Mono without Homebrew, Verdana with it). That substitution
//      is why the UI could look *monospaced* rather than merely unthemed.
//
// The rule at the bottom of the file is the fix for (2), and it is verified: with this file
// in place, `AdwaitaSans-Regular.ttf` is mapped, the Fontconfig error is gone, zero files
// below /opt/homebrew or /usr/local are opened, and the window renders in Adwaita Sans.
//
// NOTHING IN THIS FILE MAY BE AN ABSOLUTE HOST PATH. `prefix="relative"` resolves against the
// directory holding this file (<bundle>/gtk/etc/fonts), so `../../share/fonts` is
// <bundle>/gtk/share/fonts in any installation, moved anywhere. The system font directories
// are absolute on purpose: they are macOS's, present on every Mac, and they are where the
// glyph fallback for umlauts, emoji and CJK comes from.
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

/** Where the bundle keeps it, relative to the bundle root (`gtk/`). */
export const DARWIN_FONTS_CONF_PATH = 'etc/fonts/fonts.conf';

/**
 * The configuration, as text.
 *
 * Kept minimal on purpose: every `<match>` rule here is a claim about how text must look, and
 * a stock `conf.d` tree (35 files on the build host) would be a second, drifting copy of
 * fontconfig's own defaults. Families are resolved by name against the `<dir>` entries; the
 * generic aliases below, and the spellings that reach them, are the only ones GTK and pango ask for.
 */
export function renderDarwinFontsConf() {
    return `<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- Generated by packages/node-gi/scripts/fontconfig-darwin.mjs — do not edit in a bundle.
     Relative to this file, so the bundle can be moved: ../../share/fonts is <bundle>/gtk/share/fonts. -->
<fontconfig>
  <dir prefix="relative">../../share/fonts</dir>

  <!-- macOS's own faces, for everything Adwaita Sans has no glyph for: umlauts and Latin
       ligatures come from the system collection, emoji from Apple Color Emoji, CJK and the
       Indic scripts from the Supplemental set. -->
  <dir>/System/Library/Fonts</dir>
  <dir>/System/Library/Fonts/Supplemental</dir>
  <dir>/Library/Fonts</dir>
  <dir>~/Library/Fonts</dir>

  <!-- Per-user cache, never inside the bundle: a .app in /Applications is not writable by
       the user, and a cache written at build time would name files that only existed there. -->
  <cachedir prefix="xdg">fontconfig</cachedir>

  <!-- The spellings toolkits use for the generic families (pango's default is "Sans"), and
       fontconfig's 49-sansserif.conf: a family with no generic behind it falls back to
       sans-serif. Without them an unknown family matched whatever face scored best among the
       system dirs above — on the macOS Intel runner one with Tamil glyphs, which the
       font-script-coverage oracle caught. Before the generic aliases, which expand them. -->
  <alias binding="same"><family>Sans</family><prefer><family>sans-serif</family></prefer></alias>
  <alias binding="same"><family>Sans Serif</family><prefer><family>sans-serif</family></prefer></alias>
  <alias binding="same"><family>Serif</family><prefer><family>serif</family></prefer></alias>
  <alias binding="same"><family>Monospace</family><prefer><family>monospace</family></prefer></alias>
  <alias binding="same"><family>Mono</family><prefer><family>monospace</family></prefer></alias>
  <match target="pattern">
    <test qual="all" name="family" compare="not_eq"><string>sans-serif</string></test>
    <test qual="all" name="family" compare="not_eq"><string>serif</string></test>
    <test qual="all" name="family" compare="not_eq"><string>monospace</string></test>
    <edit name="family" mode="append_last"><string>sans-serif</string></edit>
  </match>

  <alias><family>sans-serif</family><prefer><family>Adwaita Sans</family><family>Helvetica</family></prefer></alias>
  <alias><family>monospace</family><prefer><family>Adwaita Mono</family><family>Menlo</family></prefer></alias>
  <alias><family>serif</family><prefer><family>Times New Roman</family></prefer></alias>

  <!-- Why this rule exists, in one line: GTK's macOS backend sets gtk-font-name to
       .AppleSystemUIFont, which is a CoreText alias with no fontconfig family behind it. -->
  <match target="pattern">
    <test name="family"><string>.AppleSystemUIFont</string></test>
    <edit name="family" mode="assign" binding="strong"><string>Adwaita Sans</string></edit>
  </match>
  <!-- The same alias spelling on older macOS releases, and what a caller asking for the UI
       face by intention rather than by Apple's name gets. -->
  <match target="pattern">
    <test name="family"><string>.SF NS</string></test>
    <edit name="family" mode="assign" binding="strong"><string>Adwaita Sans</string></edit>
  </match>
  <match target="pattern">
    <test name="family"><string>system-ui</string></test>
    <edit name="family" mode="assign" binding="strong"><string>Adwaita Sans</string></edit>
  </match>
</fontconfig>
`;
}

/**
 * Stage the config into a finished bundle tree.
 *
 * Called by the darwin builder AFTER the faces are staged, because the `<dir>` above is a
 * promise about them: a config that points at an empty directory resolves every GNOME family
 * to a system substitute and reports nothing.
 *
 * @param {string} outDir the bundle root (`…/gtk`)
 * @returns {string} absolute path of the written file
 */
export function stageDarwinFontconfig(outDir) {
    const fontDir = join(outDir, 'share', 'fonts');
    if (!existsSync(fontDir)) {
        // Loud rather than silent: this is the state that shipped for months — a bundle with
        // a config, no faces, and a UI that renders in Helvetica without an error.
        throw new Error(
            `stageDarwinFontconfig: ${fontDir} does not exist, so the generated fonts.conf would ` +
                'point at nothing. Stage the faces first (see bundle-fonts.mjs).',
        );
    }
    const target = join(outDir, DARWIN_FONTS_CONF_PATH);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, renderDarwinFontsConf());
    return target;
}
