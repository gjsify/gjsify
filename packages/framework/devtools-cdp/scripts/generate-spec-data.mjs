#!/usr/bin/env node
// Generate src/spec-data.ts — a pruned, embedded snapshot of the WebKit Remote
// Inspector Protocol (the 27 domain JSONs from refs/webkit), so @gjsify/devtools-cdp
// carries no refs/webkit dependency at runtime. Re-run when the checked-out
// WebKit protocol changes, then commit src/spec-data.ts (and `oxfmt --write` it):
//
//   node scripts/generate-spec-data.mjs [protocolDir]
//
// protocolDir defaults to the repo's refs/webkit protocol path; pass it
// explicitly when running from a git worktree without the submodule checked out
// (e.g. point at the main checkout's refs/webkit).

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const DEFAULT_PROTO_DIR = resolve(here, '../../../../refs/webkit/Source/JavaScriptCore/inspector/protocol');
const protoDir = process.argv[2] ? resolve(process.argv[2]) : DEFAULT_PROTO_DIR;
const outFile = resolve(here, '../src/spec-data.ts');

/** Keep only the fields the tool-generator + $ref resolution use. */
function pruneParam(p) {
    const out = { name: p.name };
    if (p.type !== undefined) out.type = p.type;
    if (p.$ref !== undefined) out.$ref = p.$ref;
    if (p.optional) out.optional = true;
    if (p.items !== undefined) {
        const it = {};
        if (p.items.type !== undefined) it.type = p.items.type;
        if (p.items.$ref !== undefined) it.$ref = p.items.$ref;
        out.items = it;
    }
    if (Array.isArray(p.enum)) out.enum = p.enum;
    if (p.description) out.description = p.description;
    return out;
}

function pruneCommand(c) {
    const out = { name: c.name };
    if (c.description) out.description = c.description;
    if (Array.isArray(c.parameters) && c.parameters.length) out.parameters = c.parameters.map(pruneParam);
    if (Array.isArray(c.returns) && c.returns.length) out.returns = c.returns.map(pruneParam);
    if (c.async) out.async = true;
    return out;
}

function pruneType(t) {
    const out = { id: t.id, type: t.type };
    if (Array.isArray(t.enum)) out.enum = t.enum;
    if (Array.isArray(t.properties) && t.properties.length) out.properties = t.properties.map(pruneParam);
    return out;
}

const files = readdirSync(protoDir)
    .filter((f) => f.endsWith('.json'))
    .sort();

const domains = [];
for (const file of files) {
    const json = JSON.parse(readFileSync(join(protoDir, file), 'utf8'));
    // GenericTypes.json has no `domain` field — name it from the file so its
    // global types still index under a stable key (+ the bare TypeName).
    const domain = json.domain ?? file.replace(/\.json$/, '');
    const entry = { domain };
    if (Array.isArray(json.types) && json.types.length) entry.types = json.types.map(pruneType);
    if (Array.isArray(json.commands) && json.commands.length) entry.commands = json.commands.map(pruneCommand);
    domains.push(entry);
}

const commandCount = domains.reduce((n, d) => n + (d.commands?.length ?? 0), 0);
const source = { generator: 'scripts/generate-spec-data.mjs', domains: domains.length, commands: commandCount };

const banner = `// AUTO-GENERATED by scripts/generate-spec-data.mjs — DO NOT EDIT BY HAND.
// A pruned snapshot of the WebKit Remote Inspector Protocol (refs/webkit). Re-run
// the generator + \`oxfmt --write\` after a protocol bump. ${domains.length} domains, ${commandCount} commands.
`;
const body = `import type { ProtocolDomain } from './protocol-spec.js';

export const PROTOCOL_SOURCE = ${JSON.stringify(source, null, 4)} as const;

export const PROTOCOL_SPEC: ProtocolDomain[] = ${JSON.stringify(domains, null, 4)};
`;

writeFileSync(outFile, `${banner}\n${body}`);
console.log(`[generate-spec-data] wrote ${outFile} — ${domains.length} domains, ${commandCount} commands`);
